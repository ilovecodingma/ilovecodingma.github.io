import re


def _jong(w):
    for ch in reversed(w.strip()):
        if '가' <= ch <= '힣':
            return (ord(ch) - 0xAC00) % 28
        if ch.isdigit():
            return 1 if ch in '0136' + '78' else 0
    return 0


def josa(w, a, b):
    """받침 있으면 a, 없으면 b (은/는, 이/가, 을/를, 과/와)"""
    return a if _jong(w) else b


def ro(w):
    j = _jong(w)
    return '로' if j == 0 or j == 8 else '으로'


