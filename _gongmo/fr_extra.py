def pairs(r, RS, cat_fn, have_photo, n=4):
    """함께 먹으면 좋은 메뉴: 분류 짝(국물↔밥·반찬 …), 사진 있는 것 우선, 이름이 겹치지 않게."""
    want = PAIR.get(cat_fn(r['n']), ['국물', '밥'])
    pool = [x for x in RS if x is not r and cat_fn(x['n']) in want and not (set(x['need']) & set(r['need']) == set(x['need']))]
    pool.sort(key=lambda x: (not have_photo(x['n']), x['m'], len(x['need']), hash((r['n'], x['n'])) % 997))
    out, used = [], set()
    for x in pool:
        c = cat_fn(x['n'])
        if sum(1 for y in out if cat_fn(y['n']) == c) >= 2: continue
        out.append(x)
        if len(out) >= n: break
    return out
